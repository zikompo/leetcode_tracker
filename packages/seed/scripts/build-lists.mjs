#!/usr/bin/env node
// Regenerates src/neetcode.data.ts: membership of Blind 75, NeetCode 150 and NeetCode 250.
//
// Source: neetcode.io's own app bundle, which flags each problem with `blind75`, `neetcode150`
// and `neetcode250`. Only identifying facts are kept (slug, number, title, difficulty,
// category): no problem statements.
//
//   node scripts/build-lists.mjs                    # fetch the live site
//   node scripts/build-lists.mjs --bundle main.js   # use a saved copy of the bundle
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../src/neetcode.data.ts");

async function loadBundle() {
  const i = process.argv.indexOf("--bundle");
  if (i !== -1) return readFile(process.argv[i + 1], "utf8");
  const html = await (await fetch("https://neetcode.io/")).text();
  const main = /src="(main\.[\w]+\.js)"/.exec(html)?.[1];
  if (!main) throw new Error("Couldn't find neetcode.io's main bundle");
  return (await fetch(`https://neetcode.io/${main}`)).text();
}

const bundle = await loadBundle();
const objects = bundle.match(/\{[^{}]*?(?:neetcode250|neetcode150|blind75):!0[^{}]*\}/g) ?? [];
const field = (o, k) => {
  const m = new RegExp(`(?:^|[,{])${k}:("(?:[^"\\\\]|\\\\.)*"|!0|!1)`).exec(o);
  if (!m) return undefined;
  return m[1] === "!0" ? true : m[1] === "!1" ? false : JSON.parse(m[1]);
};

const rows = objects.map((o) => {
  const code = field(o, "code"); // "0217-contains-duplicate"
  const flags = [
    field(o, "blind75") && "B",
    field(o, "neetcode150") && "N",
    field(o, "neetcode250") && "F",
  ]
    .filter(Boolean)
    .join("");
  return [
    field(o, "link").replace(/\/$/, ""),
    String(Number(code.split("-")[0])),
    field(o, "problem"),
    field(o, "difficulty"),
    field(o, "pattern"),
    flags,
  ];
});
const count = (f) => rows.filter((r) => r[5].includes(f)).length;
const counts = { blind75: count("B"), neetcode150: count("N"), neetcode250: count("F") };
if (counts.blind75 !== 75 || counts.neetcode150 !== 150 || counts.neetcode250 !== 250) {
  throw new Error(
    `Unexpected list sizes ${JSON.stringify(counts)}; the site format may have changed`,
  );
}

await writeFile(
  out,
  `// Generated by scripts/build-lists.mjs from neetcode.io on ${new Date().toISOString().slice(0, 10)}. Do not edit.
// [slug, LeetCode number, title, difficulty, NeetCode category, lists: B = Blind 75, N = NeetCode 150, F = NeetCode 250]
export const NEETCODE_ROWS: ReadonlyArray<
  readonly [string, string, string, "Easy" | "Medium" | "Hard", string, string]
> = ${JSON.stringify(rows, null, 2)};
`,
);
console.log(`Wrote ${rows.length} problems`, counts);
